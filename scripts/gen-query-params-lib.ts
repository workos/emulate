/**
 * Core codegen logic for gen-query-params. Separated from the CLI entry point
 * so the transformation functions can be unit-tested independently.
 *
 * Extracts, for every operation in a WorkOS OpenAPI spec, the names of the
 * query parameters it declares, and generates
 * src/workos/generated/query-params.ts.
 */

import type { EventSchemaNode } from './gen-events-lib.js';

const METHODS = ['get', 'post', 'put', 'patch', 'delete'] as const;

export interface ParsedQueryOperation {
  /** `<METHOD> <spec path>`, e.g. "GET /organizations/{organizationId}/groups". */
  key: string;
  /** Query parameter names in the order the spec declares them. */
  params: string[];
}

interface ParameterNode {
  name?: unknown;
  in?: unknown;
  $ref?: unknown;
}

/** A parameter, following a `#/components/parameters/<Name>` reference to its target. */
function resolveParameter(node: ParameterNode, spec: EventSchemaNode): ParameterNode {
  if (typeof node.$ref !== 'string') return node;
  const name = node.$ref.replace('#/components/parameters/', '');
  const parameters = (spec.components as { parameters?: Record<string, ParameterNode> } | undefined)?.parameters;
  const target = parameters?.[name];
  if (!target) throw new Error(`Unresolved parameter reference: ${node.$ref}`);
  return target;
}

/** The key an operation is cataloged under. */
export function queryOperationKey(method: string, path: string): string {
  return `${method.toUpperCase()} ${path}`;
}

/**
 * Every operation in the spec with the query parameters it declares, sorted by
 * key. A path item's own `parameters` apply to each of its operations, and an
 * operation that declares none is still listed, with an empty list, so that
 * "takes no query parameters" and "is not in the spec" stay distinguishable.
 */
export function parseQueryParamCatalog(spec: EventSchemaNode): ParsedQueryOperation[] {
  const paths = (spec.paths ?? {}) as Record<string, Record<string, unknown> | undefined>;
  const operations: ParsedQueryOperation[] = [];

  for (const [path, item] of Object.entries(paths)) {
    if (!item) continue;
    const shared = (item.parameters ?? []) as ParameterNode[];
    for (const method of METHODS) {
      const operation = item[method] as { parameters?: ParameterNode[] } | undefined;
      if (!operation) continue;
      const params: string[] = [];
      for (const node of [...shared, ...(operation.parameters ?? [])]) {
        const parameter = resolveParameter(node, spec);
        if (parameter.in !== 'query' || typeof parameter.name !== 'string') continue;
        if (!params.includes(parameter.name)) params.push(parameter.name);
      }
      operations.push({ key: queryOperationKey(method, path), params });
    }
  }

  return operations.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
}

export function generateQueryParamsFile(operations: ParsedQueryOperation[]): string {
  const lines: string[] = [
    '/**',
    ' * Generated by scripts/gen-query-params.ts — do not edit by hand.',
    ' * Source: the @workos/openapi-spec package. Regenerate with:',
    ' *   npm run gen:query-params',
    ' *',
    ' * The query parameters each spec operation declares, keyed by',
    ' * `<METHOD> <spec path>`. An operation that declares none is listed with an',
    ' * empty array.',
    ' *',
    ' * Consumed by src/workos/strict-query-operations.ts, which names the operations',
    ' * whose unknown query parameters production refuses; this catalog is where that',
    ' * table gets the parameters each of them accepts.',
    ' */',
    '',
    'export const QUERY_PARAMETERS = {',
  ];
  for (const { key, params } of operations) {
    lines.push(`  ${JSON.stringify(key)}: [${params.map((name) => JSON.stringify(name)).join(', ')}],`);
  }
  lines.push('} as const satisfies Record<string, readonly string[]>;');
  lines.push('');
  lines.push('/** An operation of the spec, as `<METHOD> <spec path>`. */');
  lines.push('export type QueryOperation = keyof typeof QUERY_PARAMETERS;');
  lines.push('');
  return lines.join('\n');
}
