import { buildSchema } from 'graphql';

/**
 * Where WorkOS publishes the Widgets API (Client GraphQL API) schema. Production refuses
 * introspection, so the download is the only machine-readable source of the schema.
 */
export const WIDGETS_API_SCHEMA_URL = 'https://workos.com/docs/assets/widgets-api-schema.graphql';

/**
 * Escape `sdl` so it round-trips through a backtick template literal: backslashes first, then
 * the two sequences a template literal interprets. Nothing else in SDL needs escaping.
 */
export function escapeTemplateLiteral(text: string): string {
  return text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

/**
 * The generated module: the SDL as one exported string. The schema is validated before it is
 * written, so a truncated or redirected download fails here rather than at the first request.
 */
export function generateWidgetsSchemaFile(sdl: string, source: string): string {
  buildSchema(sdl);

  return [
    '/**',
    ' * Generated by scripts/gen-widgets-schema.ts — do not edit by hand.',
    ` * Source: ${source}`,
    ' * Regenerate with:',
    ' *   bun run gen:widgets-schema',
    ' *',
    ' * The Widgets API (Client GraphQL API) schema that `@workos-inc/widgets` is generated',
    ' * against, as production publishes it. `POST /client/graphql` validates every request',
    ' * against it, so a query the widgets send that the emulator does not answer fails as',
    ' * unimplemented rather than as unknown.',
    ' */',
    '',
    `export const WIDGETS_API_SCHEMA_SDL = \`${escapeTemplateLiteral(sdl)}\`;`,
    '',
  ].join('\n');
}
